internal fun DirectoryProperty.getAndDelete(): File {
    val file = get().asFile
    if (file.isDirectory) {
        file.deleteRecursively()
    } else {
        file.delete()
    }
    return file
}

internal const val POSTHOG_CLI_DEFAULT_EXECUTABLE = "posthog-cli"

internal const val POSTHOG_RELEASE_MODE_PROPERTY = "posthog.releaseMode"

/**
 * The property no longer does anything: the mapping always binds to the release the build creates.
 * The POSTHOG_RELEASE_MODE environment variable stays silent here on purpose, because it still
 * steers the sourcemap and hermes uploads of other PostHog tools, so a warning about it would not
 * be actionable.
 */
internal fun warnIfDeprecatedReleaseModeSet(project: Project) {
    val value = project.findProperty(POSTHOG_RELEASE_MODE_PROPERTY)?.toString()?.trim()
    if (value.isNullOrEmpty()) {
        return
    }
    project.logger.warn(
        "[PostHog] $POSTHOG_RELEASE_MODE_PROPERTY is deprecated and ignored. The proguard " +
            "mapping uploads bound to the release this build creates. Remove the property.",
    )
}

internal const val POSTHOG_DOTENV_FILE_PROPERTY = "posthog.dotenvFile"

/**
 * Value of the posthog.dotenvFile gradle property as an absolute path, or null
 * when unset/blank. Relative values resolve against the root project so a
 * single gradle.properties entry works from any module. The path reaches
 * posthog-cli (>= 0.8.4) as POSTHOG_CLI_DOTENV_FILE — process env still wins
 * inside the CLI, and a missing file is a warning there, not a failure.
 */
internal fun resolvePostHogDotenvFile(project: Project): String? {
    val value = project.findProperty(POSTHOG_DOTENV_FILE_PROPERTY)?.toString()?.trim()
    if (value.isNullOrEmpty()) {
        return null
    }
    val file = File(value)
    return if (file.isAbsolute) file.path else File(project.rootDir, value).path
}

/**
 * Locates posthog-cli for builds whose environment lacks the shell PATH —
 * IDE-launched Gradle daemons don't source shell profiles, so a CLI installed
 * via nvm/npm is invisible to a plain PATH lookup. An explicitly configured
 * executable is used verbatim. The existing PATH and global install lookup keeps
 * its precedence, with project-local npm launchers added as the final fallback.
 *
 * [workingDirectory] is the Android Gradle root. Its parent is checked as well
 * because React Native projects normally keep node_modules beside android/.
 */
internal fun resolvePostHogCliExecutable(
    configured: String,
    logger: Logger,
    environment: Map<String, String> = System.getenv(),
    home: File = File(System.getProperty("user.home")),
    workingDirectory: File? = null,
    isWindows: Boolean = Os.isFamily(Os.FAMILY_WINDOWS),
    cliInstallLocations: List<File>? = null,
    nodeInstallLocations: List<File>? = null,
    warnWhenMissing: Boolean = true,
): String {
    if (configured != POSTHOG_CLI_DEFAULT_EXECUTABLE) {
        return configured
    }
    if (isWindows) {
        // A native posthog-cli.exe runs directly, so its arguments never pass through cmd.
        val pathDirectories = pathValue(environment)?.split(File.pathSeparator).orEmpty().filter { it.isNotEmpty() }
        pathDirectories
            .map { File(it, "$configured.exe") }
            .firstOrNull { it.isRunnableFile(isWindows = true) }
            ?.let { return it.absolutePath }
        // The npm .cmd shim only starts the native binary that the package installed, and cmd
        // would run a `&` in a path or a release version as a second command.
        val shims =
            pathDirectories.map { File(it, "$configured.cmd") } +
                listOfNotNull(workingDirectory, workingDirectory?.parentFile)
                    .distinct()
                    .map { File(it, "node_modules/.bin/$configured.cmd") }
        shims
            .filter { it.isFile }
            .firstNotNullOfOrNull { npmInstalledExe(it) }
            ?.let { return it.absolutePath }
        // cmd resolves the bare name, for example to an npm shim without its binary.
        return configured
    }

    val launcherName = configured

    // Resolve a PATH hit to an absolute path instead of keeping the bare name:
    // a bare name is resolved against the daemon process's own environment,
    // which can differ from the build environment (IDE-launched daemons).
    val onPathDir =
        environment["PATH"]
            ?.split(File.pathSeparator)
            ?.firstOrNull { File(it, launcherName).isRunnableFile(isWindows) }
    if (onPathDir != null) {
        return File(onPathDir, launcherName).absolutePath
    }

    if (!isWindows) {
        val candidates =
            cliInstallLocations ?: buildList {
                add(File(home, ".posthog/posthog-cli"))
                addAll(nodeVersionBins(File(home, ".nvm/versions/node")))
                File("/opt/homebrew/Cellar/nvm").listFilesSafe().forEach { cellar ->
                    addAll(nodeVersionBins(File(cellar, "versions/node")))
                }
                add(File("/usr/local/bin/posthog-cli"))
                add(File("/opt/homebrew/bin/posthog-cli"))
                add(File(home, ".cargo/bin/posthog-cli"))
                add(File(home, ".local/bin/posthog-cli"))
            }

        val found = candidates.firstOrNull { it.isRunnableFile(isWindows = false) }
        if (found != null) {
            logger.info("posthog-cli not on PATH, using ${found.absolutePath}")
            return found.absolutePath
        }
    }

    val localLauncher =
        listOfNotNull(workingDirectory, workingDirectory?.parentFile)
            .distinct()
            .map { File(it, "node_modules/.bin/$launcherName") }
            .firstOrNull { it.isRunnableFile(isWindows) }
    val nodeExecutable = resolveNodeExecutable(environment, home, isWindows, nodeInstallLocations)
    if (localLauncher != null && nodeExecutable != null) {
        logger.info("using project-local posthog-cli at ${localLauncher.absolutePath}")
        return localLauncher.absolutePath
    }

    if (warnWhenMissing) {
        logger.warn(
            "posthog-cli not found in the project, on PATH, or in known install locations; " +
                "install it (npm install --save-dev @posthog/cli or npm install -g @posthog/cli) " +
                "or set postHogExecutable on the task.",
        )
    }
    return configured
}

/**
 * Whether [executable], as [resolvePostHogCliExecutable] returned it, can run. A path must point
 * at a file. A bare name must be on PATH: the resolver returns the bare name when it finds nothing,
 * except on Windows, where cmd also runs the npm `.cmd` shim by its bare name.
 */
internal fun isPostHogCliInstalled(
    executable: String,
    environment: Map<String, String>,
    isWindows: Boolean = Os.isFamily(Os.FAMILY_WINDOWS),
): Boolean {
    if (executable.contains('/') || executable.contains('\\')) {
        return File(executable).isRunnableFile(isWindows)
    }
    val names = if (isWindows) listOf("$executable.exe", "$executable.cmd") else listOf(executable)
    return pathValue(environment)
        ?.split(File.pathSeparator)
        ?.any { dir -> dir.isNotEmpty() && names.any { File(dir, it).isRunnableFile(isWindows) } }
        ?: false
}

/**
 * The native binary that the npm package of posthog-cli installs and that its `.cmd` shim starts.
 * A global install puts the shim in the npm prefix, next to `node_modules`. A project install puts
 * it in `node_modules/.bin`.
 */
internal fun npmInstalledExe(shim: File): File? {
    val shimDirectory = shim.absoluteFile.parentFile ?: return null
    val binary = "@posthog/cli/node_modules/.bin_real/$POSTHOG_CLI_DEFAULT_EXECUTABLE.exe"
    return listOfNotNull(
        File(shimDirectory, "node_modules/$binary"),
        shimDirectory.parentFile?.let { File(it, binary) },
    ).firstOrNull { it.isFile }
}

internal fun runsThroughCmd(
    executable: String,
    isWindows: Boolean = Os.isFamily(Os.FAMILY_WINDOWS),
): Boolean = isWindows && !executable.endsWith(".exe", ignoreCase = true)

// ProcessBuilder quotes an argument that holds a space, and cmd reads & | < > ^ literally inside
// quotes. Outside quotes it runs them as operators, and it expands %VAR% and !VAR! in both places.
// A quote in the value ends the quoting, and a line break ends the command.
private const val CMD_UNSAFE_CHARACTERS = "&|<>^%!\"\r\n"

/** The first of [values] that cmd would not pass on unchanged, or null when all are safe. */
internal fun firstUnsafeForCmd(values: List<String>): String? = values.firstOrNull { value -> value.any { it in CMD_UNSAFE_CHARACTERS } }

internal fun resolveNodeExecutable(
    environment: Map<String, String> = System.getenv(),
    home: File = File(System.getProperty("user.home")),
    isWindows: Boolean = Os.isFamily(Os.FAMILY_WINDOWS),
    knownInstallLocations: List<File>? = null,
): String? {
    val executableName = if (isWindows) "node.exe" else "node"
    val onPath =
        pathValue(environment)
            ?.split(File.pathSeparator)
            ?.map { File(it, executableName) }
            ?.firstOrNull { it.isRunnableFile(isWindows) }
    if (onPath != null) {
        return onPath.absolutePath
    }
    if (isWindows) {
        return null
    }

    val candidates =
        knownInstallLocations ?: buildList {
            addAll(nodeVersionExecutables(File(home, ".nvm/versions/node"), executableName))
            File("/opt/homebrew/Cellar/nvm").listFilesSafe().forEach { cellar ->
                addAll(nodeVersionExecutables(File(cellar, "versions/node"), executableName))
            }
            add(File("/usr/local/bin/node"))
            add(File("/opt/homebrew/bin/node"))
            add(File(home, ".local/bin/node"))
        }
    return candidates.firstOrNull { it.isRunnableFile(isWindows = false) }?.absolutePath
}

internal fun prependExecutableDirectoriesToPath(
    executables: List<String>,
    environment: Map<String, String>,
): Pair<String, String> {
    val pathKey = environment.keys.firstOrNull { it.equals("PATH", ignoreCase = true) } ?: "PATH"
    val path = environment[pathKey].orEmpty()
    val binDirectories = executables.mapNotNull { File(it).parent }.distinct()
    val entries = if (path.isEmpty()) binDirectories else binDirectories + path
    return pathKey to entries.joinToString(File.pathSeparator)
}

private fun pathValue(environment: Map<String, String>): String? =
    environment.entries.firstOrNull { it.key.equals("PATH", ignoreCase = true) }?.value

private fun File.isRunnableFile(isWindows: Boolean): Boolean = isFile && (isWindows || canExecute())

private fun File.listFilesSafe(): List<File> = listFiles()?.toList() ?: emptyList()

/** `<root>/vX.Y.Z/bin/posthog-cli` candidates, newest node version first. */
private fun nodeVersionBins(root: File): List<File> = nodeVersionExecutables(root, "posthog-cli")

private fun nodeVersionExecutables(
    root: File,
    executableName: String,
): List<File> =
    root.listFilesSafe()
        .sortedWith(NODE_VERSION_DIR_ORDER.reversed())
        .map { File(it, "bin/$executableName") }

private val NODE_VERSION_DIR_ORDER =
    Comparator<File> { a, b ->
        val x = versionKey(a.name)
        val y = versionKey(b.name)
        for (i in 0 until maxOf(x.size, y.size)) {
            val cmp = x.getOrElse(i) { 0L }.compareTo(y.getOrElse(i) { 0L })
            if (cmp != 0) return@Comparator cmp
        }
        0
    }

private fun versionKey(name: String): List<Long> = Regex("\\d+").findAll(name).mapNotNull { it.value.toLongOrNull() }.toList()
